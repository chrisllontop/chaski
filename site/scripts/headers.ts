// Runs after `vite build`. TanStack Start's prerendered pages hydrate from inline scripts that
// differ from page to page, so each page gets a Content-Security-Policy that allows exactly its
// own scripts by hash. Everything else keeps the strict policy in public/_headers.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const OUT = 'dist/client';
const NOT_FOUND = '404.html';

const POLICY = [
  "default-src 'none'",
  "script-src 'self'",
  "style-src 'self'",
  "img-src 'self'",
  "font-src 'self'",
  "connect-src 'self'",
  "base-uri 'none'",
  "form-action 'none'",
  "frame-ancestors 'none'",
];

const htmlFiles = (dir: string): string[] =>
  readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) return htmlFiles(path);
    return entry.name.endsWith('.html') ? [path] : [];
  });

// docs/install.html is served at /docs/install, and index.html at /.
const urlPath = (file: string) => {
  const path = `/${relative(OUT, file).replace(/\.html$/, '')}`;
  return path === '/index' ? '/' : path;
};

const INLINE_SCRIPT = /<script(?![^>]*\ssrc=)[^>]*>([\s\S]*?)<\/script>/g;

const hash = (script: string) =>
  `'sha256-${createHash('sha256').update(script, 'utf8').digest('base64')}'`;

const policyWith = (hashes: string[]) =>
  POLICY.map((directive) =>
    directive.startsWith('script-src') ? [directive, ...hashes].join(' ') : directive,
  ).join('; ');

const failures: string[] = [];
const rules: string[] = [];

for (const file of htmlFiles(OUT).sort()) {
  let html = readFileSync(file, 'utf8');

  if (/\sstyle=["']|<style[\s>]/.test(html)) {
    failures.push(`${relative(OUT, file)} has an inline style, which the policy blocks`);
  }

  // The 404 page answers at every unknown path, where hydrating it would fight the router, and
  // it needs no script: it ships as plain HTML under the base policy.
  if (relative(OUT, file) === NOT_FOUND) {
    html = html
      .replace(/<script\b[\s\S]*?<\/script>/g, '')
      .replace(/<link rel="modulepreload"[^>]*>/g, '');
    writeFileSync(file, html);
    continue;
  }

  const hashes = [...new Set([...html.matchAll(INLINE_SCRIPT)].map(([, body = '']) => hash(body)))];
  rules.push(
    [
      urlPath(file),
      '  ! Content-Security-Policy',
      `  Content-Security-Policy: ${policyWith(hashes)}`,
    ].join('\n'),
  );
}

if (failures.length > 0) {
  console.error(failures.join('\n'));
  process.exit(1);
}

const headersFile = join(OUT, '_headers');
const base = readFileSync(headersFile, 'utf8').replaceAll('{{POLICY}}', POLICY.join('; '));
writeFileSync(
  headersFile,
  `${base.trimEnd()}\n\n# Generated by scripts/headers.ts: each page's own inline scripts, by hash.\n${rules.join('\n\n')}\n`,
);

// Links to a section of a page reach the sitemap as pages of their own.
const sitemapFile = join(OUT, 'sitemap.xml');
writeFileSync(
  sitemapFile,
  readFileSync(sitemapFile, 'utf8').replace(
    /\s*<url>\s*<loc>[^<]*#[^<]*<\/loc>[\s\S]*?<\/url>/g,
    '',
  ),
);
rmSync(join(OUT, 'pages.json'), { force: true });

console.log(`headers: a policy for each of ${rules.length} pages, ${NOT_FOUND} without scripts`);
