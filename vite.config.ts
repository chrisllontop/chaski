import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import tailwindcss from '@tailwindcss/vite';
import react from '@vitejs/plugin-react';
import { defineConfig, type Plugin } from 'vite';

const target = fileURLToPath(new URL('./src/generated/dashboard.ts', import.meta.url));

const textTypes: Record<string, string> = {
  css: 'text/css; charset=utf-8',
  js: 'text/javascript; charset=utf-8',
  json: 'application/json; charset=utf-8',
  svg: 'image/svg+xml; charset=utf-8',
  txt: 'text/plain; charset=utf-8',
};

const binaryTypes: Record<string, string> = {
  avif: 'image/avif',
  gif: 'image/gif',
  ico: 'image/x-icon',
  jpeg: 'image/jpeg',
  jpg: 'image/jpeg',
  png: 'image/png',
  webp: 'image/webp',
  woff: 'font/woff',
  woff2: 'font/woff2',
};

type Asset = { type: string; body: string; base64?: true };

// The package serves the dashboard from its own bundle, so the build becomes a TypeScript module
// instead of files the host would have to upload or route.
const embedDashboard = (): Plugin => ({
  name: 'chaski:embed-dashboard',
  apply: 'build',
  // index.html only joins the bundle in Vite's own post-phase generateBundle.
  enforce: 'post',
  generateBundle(_, bundle) {
    let shell = '';
    const assets: Record<string, Asset> = {};
    for (const file of Object.values(bundle)) {
      const content = file.type === 'chunk' ? file.code : file.source;
      const extension = file.fileName.split('.').pop() ?? '';
      if (file.fileName === 'index.html') {
        shell = String(content);
      } else if (textTypes[extension]) {
        const body = typeof content === 'string' ? content : new TextDecoder().decode(content);
        assets[file.fileName] = { type: textTypes[extension], body };
      } else {
        const type = binaryTypes[extension] ?? 'application/octet-stream';
        assets[file.fileName] = {
          type,
          body: Buffer.from(content).toString('base64'),
          base64: true,
        };
      }
    }
    if (!shell.includes('<head>')) {
      this.error('index.html needs a <head> tag: the server injects the base path after it.');
    }
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(
      target,
      [
        '// Generated by vite.config.ts from src/dashboard. Do not edit.',
        `export const shell: string = ${JSON.stringify(shell)};`,
        `export const assets: Record<string, { type: string; body: string; base64?: true }> = ${JSON.stringify(assets)};`,
        '',
      ].join('\n'),
    );
  },
});

export default defineConfig({
  root: 'src/dashboard',
  base: './',
  plugins: [react(), tailwindcss(), embedDashboard()],
  build: {
    write: false,
    // Inlined data: URLs would need a looser Content-Security-Policy on the shell.
    assetsInlineLimit: 0,
  },
});
